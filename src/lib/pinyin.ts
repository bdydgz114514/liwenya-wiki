export function initialOf(text?: string): string {
  const s = (text ?? '').trim();
  if (!s) return '#';
  const first = s[0];
  if (/[A-Za-z]/.test(first)) return first.toUpperCase();
  if (/[0-9]/.test(first)) return '#';
  return MAP[first] ?? '#';
}

